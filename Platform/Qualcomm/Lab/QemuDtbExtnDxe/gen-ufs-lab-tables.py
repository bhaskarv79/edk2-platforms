"""Generate the lab QcomUfsHcDxe PHY tables for the QEMU Qualcomm UFS model
from the Linux kernel's SC7280 QMP UFS PHY tables.

  gen-ufs-lab-tables.py <linux tree> > UfsLabPhyTables.h

The PHY tables (offset/value pairs written to UfsMemBase + offset) are taken
from drivers/phy/qualcomm/phy-qcom-qmp-ufs.c, so that the lab programs the
PHY the way Linux does on SC7280 (Kodiak), independently of the driver
under test. The PHY sits at UfsMemBase + 0x3000 (kodiak.dtsi: UFSHCI at
0x1d84000, PHY at 0x1d87000), with Linux's QMP UFS v4 block offsets.

Lab tool, not intended for upstream.
"""
import glob
import os
import re
import sys

PHY_BASE = 0x3000
BLOCKS = {'serdes': 0x000, 'tx': 0x400, 'rx': 0x600, 'tx2': 0x800,
          'rx2': 0xA00, 'pcs': 0xC00}
# Lab table name -> list of (Linux table, block)
TABLES = [
    ('InitTable', [('sm8150_ufsphy_serdes', 'serdes')]),
    ('Lane0Table', [('sc7280_ufsphy_tx', 'tx'), ('sc7280_ufsphy_rx', 'rx')]),
    ('Lane1Table', [('sc7280_ufsphy_tx', 'tx2'), ('sc7280_ufsphy_rx', 'rx2')]),
    ('EndTable', [('sc7280_ufsphy_pcs', 'pcs')]),
    ('HsLss', [('sm8150_ufsphy_hs_b_serdes', 'serdes')]),
]


def main():
    linux = sys.argv[1]
    phy = os.path.join(linux, 'drivers/phy/qualcomm')
    src = open(os.path.join(phy, 'phy-qcom-qmp-ufs.c')).read()
    defs = {}
    for h in glob.glob(os.path.join(phy, 'phy-qcom-qmp*.h')):
        for m in re.finditer(r'#define\s+(\w+)\s+(0x[0-9a-fA-F]+)', open(h).read()):
            defs[m.group(1)] = int(m.group(2), 16)

    ver = ''
    mk = os.path.join(linux, 'Makefile')
    if os.path.exists(mk):
        v = dict(re.findall(r'^(VERSION|PATCHLEVEL|SUBLEVEL|EXTRAVERSION) = (\S*)', open(mk).read(), re.M))
        ver = 'Linux %s.%s.%s%s ' % (v.get('VERSION'), v.get('PATCHLEVEL'), v.get('SUBLEVEL'), v.get('EXTRAVERSION', ''))
    out = ['/** @file',
           '  SC7280 QMP UFS PHY programming for the QEMU Qualcomm UFS model, as',
           '  QcomUfsHcDxe PHY tables: {Flags, Offset from UfsMemBase, Value}.',
           '',
           '  Generated by gen-ufs-lab-tables.py from %sdrivers/phy/qualcomm/' % ver,
           '  phy-qcom-qmp-ufs.c (sm8150 serdes, sc7280 tx/rx/pcs); do not edit.',
           '  Lab file, not intended for upstream.',
           '',
           '  Copyright (c) Qualcomm Technologies, Inc. and/or its subsidiaries.<BR>',
           '  SPDX-License-Identifier: BSD-2-Clause-Patent',
           '**/', '', '#pragma once', '']
    for name, parts in TABLES:
        cells = []
        for table, block in parts:
            m = re.search(r'qmp_phy_init_tbl %s\[\] = \{(.*?)\};' % table, src, re.S)
            if not m:
                sys.exit('table %s not found' % table)
            for e in re.finditer(r'QMP_PHY_INIT_CFG\((\w+),\s*(0x[0-9a-fA-F]+|\d+)\)', m.group(1)):
                off = PHY_BASE + BLOCKS[block] + defs[e.group(1)]
                cells.append('  0x0000, 0x%04X, 0x%04X,   // %s %s' % (off, int(e.group(2), 0), table, e.group(1)))
        cells.append('  0x8000, 0x0000, 0x0000    // stop')
        out.append('STATIC CONST UINT16  mUfsLab%s[] = {' % name)
        out += cells
        out += ['};', '']
    print('\n'.join(out))


if __name__ == '__main__':
    main()
